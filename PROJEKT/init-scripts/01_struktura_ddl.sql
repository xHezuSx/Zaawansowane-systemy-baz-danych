-- ----------------------------------------------------------------------------
-- 1. CZYSZCZENIE STRUKTURY (Usuwanie tabel jeśli istnieją)
-- ----------------------------------------------------------------------------
BEGIN
    FOR t IN (
        SELECT table_name 
        FROM user_tables 
        WHERE table_name IN (
            'WYNIKI_BADAN', 'BADANIA_SLOWNIK', 'POBYTY_ARCH', 'POBYTY', 
            'OSOBY_UPOWAZNIONE', 'PACJENCI', 'PERSONEL_SPECJALIZACJE', 
            'SPECJALIZACJE', 'PERSONEL', 'ODDZIALY', 'LOGI_SYSTEMOWE', 
            'PODSUMOWANIA_OKRESOWE'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/


-- ----------------------------------------------------------------------------
-- 2. TWORZENIE TABEL STRUKTURY ORGANIZACYJNEJ I PERSONELU
-- ----------------------------------------------------------------------------

-- Tabela: ODDZIALY (Oddziały szpitalne)
CREATE TABLE ODDZIALY (
    id_oddzialu     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nazwa           VARCHAR2(100) NOT NULL,
    id_ordynatora   NUMBER,
    pietro          NUMBER(2) NOT NULL,
    CONSTRAINT pk_oddzialy PRIMARY KEY (id_oddzialu),
    CONSTRAINT uk_oddzialy_nazwa UNIQUE (nazwa),
    CONSTRAINT chk_oddzialy_pietro CHECK (pietro BETWEEN -1 AND 20)
);

-- Tabela: PERSONEL (Pracownicy medyczni i administracyjni)
CREATE TABLE PERSONEL (
    id_personelu      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_oddzialu       NUMBER NOT NULL,
    imie              VARCHAR2(50) NOT NULL,
    nazwisko          VARCHAR2(50) NOT NULL,
    rola              VARCHAR2(30) NOT NULL,
    nr_pwz            VARCHAR2(7),
    stawka_godzinowa  NUMBER(8, 2) NOT NULL,
    CONSTRAINT pk_personel PRIMARY KEY (id_personelu),
    CONSTRAINT fk_personel_oddzial FOREIGN KEY (id_oddzialu) 
        REFERENCES ODDZIALY(id_oddzialu),
    CONSTRAINT uk_personel_pwz UNIQUE (nr_pwz),
    CONSTRAINT chk_personel_stawka CHECK (stawka_godzinowa > 0),
    CONSTRAINT chk_personel_rola CHECK (rola IN ('LEKARZ', 'PIELEGNIARKA', 'PIELEGNIARZ', 'RATOWNIK', 'KIEROWNIK', 'INNY'))
);

-- Złączenie cykliczne: powiązanie ordynatora oddziału z personelem
ALTER TABLE ODDZIALY 
    ADD CONSTRAINT fk_oddzialy_ordynator 
    FOREIGN KEY (id_ordynatora) REFERENCES PERSONEL(id_personelu);

-- Tabela: SPECJALIZACJE (Słownik specjalizacji lekarskich)
CREATE TABLE SPECJALIZACJE (
    id_specjalizacji NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nazwa            VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_specjalizacje PRIMARY KEY (id_specjalizacji),
    CONSTRAINT uk_specjalizacje_nazwa UNIQUE (nazwa)
);

-- Tabela: PERSONEL_SPECJALIZACJE (Relacja wiele-do-wielu: personel - specjalizacje)
CREATE TABLE PERSONEL_SPECJALIZACJE (
    id_personelu     NUMBER NOT NULL,
    id_specjalizacji NUMBER NOT NULL,
    data_uzyskania   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_personel_specjalizacje PRIMARY KEY (id_personelu, id_specjalizacji),
    CONSTRAINT fk_per_spec_personel FOREIGN KEY (id_personelu) 
        REFERENCES PERSONEL(id_personelu) ON DELETE CASCADE,
    CONSTRAINT fk_per_spec_specjalizacja FOREIGN KEY (id_specjalizacji) 
        REFERENCES SPECJALIZACJE(id_specjalizacji) ON DELETE CASCADE
);


-- ----------------------------------------------------------------------------
-- 3. TWORZENIE TABEL KARTOTEKI PACJENTÓW
-- ----------------------------------------------------------------------------

-- Tabela: PACJENCI
CREATE TABLE PACJENCI (
    id_pacjenta    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    pesel          VARCHAR2(11),
    nr_paszportu   VARCHAR2(20),
    imie           VARCHAR2(50) NOT NULL,
    nazwisko       VARCHAR2(50) NOT NULL,
    data_urodzenia DATE NOT NULL,
    plec           CHAR(1) NOT NULL,
    ulica          VARCHAR2(100),
    miasto         VARCHAR2(50) NOT NULL,
    kod_pocztowy   VARCHAR2(10),
    kraj           VARCHAR2(50) DEFAULT 'Polska' NOT NULL,
    telefon        VARCHAR2(20),
    CONSTRAINT pk_pacjenci PRIMARY KEY (id_pacjenta),
    CONSTRAINT uk_pacjenci_pesel UNIQUE (pesel),
    CONSTRAINT uk_pacjenci_paszport UNIQUE (nr_paszportu),
    CONSTRAINT chk_pacjenci_plec CHECK (plec IN ('K', 'M')),
    CONSTRAINT chk_pacjenci_identyfikator CHECK (pesel IS NOT NULL OR nr_paszportu IS NOT NULL)
);

-- Tabela: OSOBY_UPOWAZNIONE (Kontakty i osoby upoważnione przez pacjenta)
CREATE TABLE OSOBY_UPOWAZNIONE (
    id_osoby       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_pacjenta    NUMBER NOT NULL,
    imie_nazwisko  VARCHAR2(100) NOT NULL,
    relacja        VARCHAR2(50) NOT NULL,
    telefon        VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_osoby_upowaznione PRIMARY KEY (id_osoby),
    CONSTRAINT fk_osoby_pacjent FOREIGN KEY (id_pacjenta) 
        REFERENCES PACJENCI(id_pacjenta) ON DELETE CASCADE
);


-- ----------------------------------------------------------------------------
-- 4. TWORZENIE TABEL RUCHU CHORYCH (POBYTY) I DIAGNOSTYKI (EDM)
-- ----------------------------------------------------------------------------

-- Tabela: POBYTY (Hospitalizacje pacjentów na oddziałach)
CREATE TABLE POBYTY (
    id_pobytu       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_pacjenta     NUMBER NOT NULL,
    id_oddzialu     NUMBER NOT NULL,
    id_lekarza      NUMBER NOT NULL,
    data_przyjecia  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    data_wypisu     TIMESTAMP,
    kod_icd10       VARCHAR2(10),
    koszt_leczenia  NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    CONSTRAINT pk_pobyty PRIMARY KEY (id_pobytu),
    CONSTRAINT fk_pobyty_pacjent FOREIGN KEY (id_pacjenta) 
        REFERENCES PACJENCI(id_pacjenta),
    CONSTRAINT fk_pobyty_oddzial FOREIGN KEY (id_oddzialu) 
        REFERENCES ODDZIALY(id_oddzialu),
    CONSTRAINT fk_pobyty_lekarz FOREIGN KEY (id_lekarza) 
        REFERENCES PERSONEL(id_personelu),
    CONSTRAINT chk_pobyty_daty CHECK (data_wypisu IS NULL OR data_wypisu >= data_przyjecia),
    CONSTRAINT chk_pobyty_koszt CHECK (koszt_leczenia >= 0)
);

-- Tabela: BADANIA_SLOWNIK (Definicje badań laboratoryjnych i norm)
CREATE TABLE BADANIA_SLOWNIK (
    id_badania     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    kod_badania    VARCHAR2(20) NOT NULL,
    nazwa          VARCHAR2(100) NOT NULL,
    jednostka      VARCHAR2(20),
    norma_min      NUMBER(10, 3),
    norma_max      NUMBER(10, 3),
    CONSTRAINT pk_badania_slownik PRIMARY KEY (id_badania),
    CONSTRAINT uk_badania_kod UNIQUE (kod_badania),
    CONSTRAINT chk_badania_normy CHECK (norma_max IS NULL OR norma_min IS NULL OR norma_max >= norma_min)
);

-- Tabela: WYNIKI_BADAN (Wyniki badań zrealizowanych w ramach pobytu)
CREATE TABLE WYNIKI_BADAN (
    id_wyniku     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_pobytu     NUMBER NOT NULL,
    id_badania    NUMBER NOT NULL,
    wartosc       NUMBER(10, 3) NOT NULL,
    czy_w_normie  CHAR(1) DEFAULT 'T' NOT NULL,
    data_badania  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    zrodlo_pliku  VARCHAR2(255),
    CONSTRAINT pk_wyniki_badan PRIMARY KEY (id_wyniku),
    CONSTRAINT fk_wyniki_pobyt FOREIGN KEY (id_pobytu) 
        REFERENCES POBYTY(id_pobytu) ON DELETE CASCADE,
    CONSTRAINT fk_wyniki_badanie FOREIGN KEY (id_badania) 
        REFERENCES BADANIA_SLOWNIK(id_badania),
    CONSTRAINT chk_wyniki_norma CHECK (czy_w_normie IN ('T', 'N'))
);


-- ----------------------------------------------------------------------------
-- 5. TABELE ARCHIWALNE, AUDYTOWE I RAPORTOWE
-- ----------------------------------------------------------------------------

-- Tabela: POBYTY_ARCH (Historia usuniętych rekordów hospitalizacji)
CREATE TABLE POBYTY_ARCH (
    id_arch         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_pobytu       NUMBER NOT NULL,
    id_pacjenta     NUMBER NOT NULL,
    id_oddzialu     NUMBER NOT NULL,
    data_przyjecia  TIMESTAMP NOT NULL,
    data_wypisu     TIMESTAMP,
    data_usuniecia  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    uzytkownik_db   VARCHAR2(100) DEFAULT USER NOT NULL,
    CONSTRAINT pk_pobyty_arch PRIMARY KEY (id_arch)
);

-- Tabela: LOGI_SYSTEMOWE (Dedykowana tabela logowania zdarzeń)
CREATE TABLE LOGI_SYSTEMOWE (
    id_logu        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    data_zdarzenia TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    poziom         VARCHAR2(10) DEFAULT 'INFO' NOT NULL,
    modul          VARCHAR2(50) NOT NULL,
    komunikat      VARCHAR2(4000) NOT NULL,
    CONSTRAINT pk_logi_systemowe PRIMARY KEY (id_logu),
    CONSTRAINT chk_logi_poziom CHECK (poziom IN ('INFO', 'WARN', 'ERROR', 'DEBUG'))
);

-- Tabela: PODSUMOWANIA_OKRESOWE (Agregacje czasowe pod wykresy i dashboardy)
CREATE TABLE PODSUMOWANIA_OKRESOWE (
    id_podsumowania    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    typ_okresu         VARCHAR2(12) NOT NULL,
    rok                NUMBER(4) NOT NULL,
    okres_nr           NUMBER(2) NOT NULL,
    id_oddzialu        NUMBER,
    liczba_pobytow     NUMBER DEFAULT 0 NOT NULL,
    sr_czas_pobytu_dni NUMBER(8, 2) DEFAULT 0.00 NOT NULL,
    laczny_koszt       NUMBER(12, 2) DEFAULT 0.00 NOT NULL,
    CONSTRAINT pk_podsumowania_okresowe PRIMARY KEY (id_podsumowania),
    CONSTRAINT fk_podsumowania_oddzial FOREIGN KEY (id_oddzialu) 
        REFERENCES ODDZIALY(id_oddzialu) ON DELETE CASCADE,
    CONSTRAINT chk_podsumowania_typ CHECK (typ_okresu IN ('MIESIECZNY', 'KWARTALNY', 'ROCZNY')),
    CONSTRAINT chk_podsumowania_okres CHECK (okres_nr BETWEEN 1 AND 12)
);


-- ----------------------------------------------------------------------------
-- 6. INDEKSY DLA KLUCZY OBCYCH (Optymalizacja wydajności złączeń w Oracle)
-- ----------------------------------------------------------------------------
CREATE INDEX idx_personel_oddzial ON PERSONEL(id_oddzialu);
CREATE INDEX idx_oddzialy_ordynator ON ODDZIALY(id_ordynatora);
CREATE INDEX idx_per_spec_personel ON PERSONEL_SPECJALIZACJE(id_personelu);
CREATE INDEX idx_per_spec_specjalizacja ON PERSONEL_SPECJALIZACJE(id_specjalizacji);
CREATE INDEX idx_osoby_pacjent ON OSOBY_UPOWAZNIONE(id_pacjenta);
CREATE INDEX idx_pobyty_pacjent ON POBYTY(id_pacjenta);
CREATE INDEX idx_pobyty_oddzial ON POBYTY(id_oddzialu);
CREATE INDEX idx_pobyty_lekarz ON POBYTY(id_lekarza);
CREATE INDEX idx_pobyty_daty ON POBYTY(data_przyjecia, data_wypisu);
CREATE INDEX idx_wyniki_pobyt ON WYNIKI_BADAN(id_pobytu);
CREATE INDEX idx_wyniki_badanie ON WYNIKI_BADAN(id_badania);
CREATE INDEX idx_podsumowania_szukaj ON PODSUMOWANIA_OKRESOWE(rok, typ_okresu, id_oddzialu);

COMMIT;
